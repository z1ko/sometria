#!/usr/bin/env python
"""Summarize the reconstruction and forecasting runs into metrics.csv and README.md.

    uv run python results/reconstruction/gen.py

Reads `runs/reconstruction/<mask>/<corpus>/<arch>/<replicate>/<cell>/metrics.json`, the
tree `scripts/reconstruction_matrix.sh` writes. One table per mask: `random` is phase 3
(reconstruction, a diagnostic) and `suffix` is phase 4 (forecasting, ~1 s). Both are in
degrees and **lower is better**, which is the one thing that differs from every other
table in `results/` -- so the bolded cell is the minimum here, not the maximum.

Numbers are read, never transcribed, for the reason `results/probe/babel_60_convex/gen.py`
gives at length: a hand-maintained narrative ends up with provenance embedded in prose
where nothing can check it against the run. The prose above the GENERATED marker in
README.md is hand-written and survives regeneration; the pre-registration in particular
is dated by the git history of that file and must not be regenerated.

No figures. Nine cells in one unit is a table, and a nine-bar chart of it would carry
nothing the table does not -- add `figures/` when there is a second axis to plot against.
"""

import json
from pathlib import Path

import polars as pl

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
RUNS = ROOT / "runs" / HERE.name

# Width order rather than alphabetical, so a table reads narrow to wide. Same list as the
# probe's, minus nothing: a cell that was not run shows as `--`.
AXIS = ["p", "pv", "pk", "pkd"]

MASKS = {
    "random": "Reconstruction -- 75% of tokens held out uniformly (diagnostic, not a ranking)",
    "suffix": "Forecasting -- last 8 time patches (1.067 s) held out across all 43 DOFs",
}

# The forecasting floors. Model-free, so they are identical across cells by construction
# and are averaged over runs rather than tabulated per cell; a spread here would mean the
# validation split moved between runs, which is why the sd is printed.
BASELINES = ["zero_velocity", "const_velocity"]

BEGIN = "<!-- GENERATED by gen.py -- do not edit below this line -->"
END = "<!-- /GENERATED -->"


def collect() -> pl.DataFrame:
    """One row per (mask, cell, replicate), with the provenance its own metrics.json holds."""

    rows = []
    # rglob, not a fixed-depth glob: replicates nest an extra segment or two
    # (mask/corpus/arch/seed1/cell, .../seed1/rep2/cell) and a fixed depth would find the
    # canonical runs and silently skip every replicate.
    for path in sorted(RUNS.rglob("in_*/metrics.json")):
        cell = path.parent
        parts = cell.relative_to(RUNS).parts
        if len(parts) < 4:
            continue
        payload = json.loads(path.read_text())
        name = cell.name
        rows.append(
            {
                "mask": parts[0],
                "corpus": parts[1],
                "arch": parts[2],
                "replicate": "/".join(parts[3:-1]),
                "cell": name,
                "input": name.removeprefix("in_").split("__")[0],
                # Null, not a sentinel, where the objective has no reconstruction target:
                # it then groups, sorts and renders as missing instead of pretending to be
                # a fourth channel set.
                "loss": name.split("__loss_")[1] if "__loss_" in name else None,
                "epochs": payload.get("epochs"),
                "dec_depth": payload.get("dec_depth"),
                "dec_dim": payload.get("dec_dim"),
                "degrees": payload["metrics"]["degrees"],
                **{key: payload["metrics"].get(key) for key in BASELINES},
            }
        )

    if not rows:
        raise FileNotFoundError(f"no metrics.json under {RUNS}")
    return pl.DataFrame(rows)


def matrix(df: pl.DataFrame) -> str:
    """A 3x3 input-by-loss table of degrees, bolding the *lowest* cell.

    Cells hold the mean over whatever replicates exist, with the sample standard deviation
    beside it once there is more than one. A single number with no spread is a single run
    and should be read as one -- `results/decoder_capacity/README.md` is the standing
    warning about what a single seed draw is worth.
    """

    stats = {}
    for (inp, loss), group in df.group_by("input", "loss"):
        values = group["degrees"]
        stats[(inp, loss)] = (values.mean(), values.std() if len(values) > 1 else None)

    columns = [c for c in AXIS if any(loss == c for _, loss in stats)] or [None]
    best = min(mean for mean, _ in stats.values())

    header = " | ".join(f"`loss_{c}`" if c else "degrees" for c in columns)
    lines = [f"| input \\ loss | {header} |", "| :--- | " + " ".join([":---:|"] * len(columns))]
    for row in AXIS:
        if not any(inp == row for inp, _ in stats):
            continue
        cells = []
        for column in columns:
            entry = stats.get((row, column))
            if entry is None:
                cells.append("--")
                continue
            mean, sd = entry
            text = f"**{mean:.2f}**" if mean == best else f"{mean:.2f}"
            cells.append(text + (f" ±{sd:.2f}" if sd is not None else ""))
        lines.append(f"| **`in_{row}`** | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def baselines(df: pl.DataFrame) -> tuple[str, dict]:
    """The model-free forecasting floors, and the JSON the standing rules ask for."""

    payload, lines = {}, ["| baseline | degrees | protocol |", "| :--- | ---: | :--- |"]
    for name in BASELINES:
        values = df[name].drop_nulls()
        if not len(values):
            continue
        payload[name] = {
            "degrees": round(values.mean(), 4),
            "sd": round(values.std(), 4) if len(values) > 1 else None,
            "runs": len(values),
            "protocol": "exact, no model -- same windows, same horizon, same unit",
            "note": (
                "Zero-velocity holds the last observed frame for all 64 predicted frames; "
                "constant-velocity extrapolates the wrapped difference of the last two "
                "observed frames. Computed inside the same validation loop as the model, "
                "so the split and the horizon are identical by construction rather than "
                "by agreement."
            ),
        }
        spread = f" ±{values.std():.2f}" if len(values) > 1 else ""
        lines.append(f"| `{name}` | {values.mean():.2f}{spread} | exact, no model |")
    return "\n".join(lines), payload


def tables(df: pl.DataFrame) -> str:
    """The generated block: one section per mask, plus the forecasting floors."""

    blocks = [
        f"*{len(df)} runs, `dec_depth` "
        f"{df['dec_depth'].unique().to_list()} / `dec_dim` {df['dec_dim'].unique().to_list()}, "
        f"{df['epochs'].unique().to_list()} decoder epochs. Mean per-DOF angular error in "
        f"degrees -- **lower is better**. Regenerate with `gen.py`.*"
    ]
    for mask, title in MASKS.items():
        subset = df.filter(pl.col("mask") == mask)
        if subset.is_empty():
            continue
        blocks += [f"## {title}", matrix(subset)]
        if mask == "suffix":
            table, payload = baselines(subset)
            (HERE / "baselines.json").write_text(json.dumps(payload, indent=2))
            blocks += ["### Floors", table]
    return "\n\n".join(blocks)


def splice(readme: Path, generated: str) -> None:
    """Replace the generated block, leaving hand-written prose untouched."""

    block = f"{BEGIN}\n\n{generated}\n{END}"
    if readme.exists() and BEGIN in readme.read_text():
        head, _, rest = readme.read_text().partition(BEGIN)
        _, _, tail = rest.partition(END)
        readme.write_text(head + block + tail)
    else:
        readme.write_text(f"# {HERE.name}\n\n{block}\n")


def main() -> None:
    df = collect().sort("mask", "corpus", "arch", "input", "loss")
    df.write_csv(HERE / "metrics.csv")
    splice(HERE / "README.md", tables(df))
    print(f"{len(df)} runs -> {HERE / 'metrics.csv'} and README.md")


if __name__ == "__main__":
    main()
