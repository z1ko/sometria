#!/usr/bin/env python
"""Summarize the representation runs into CSVs and the tables in README.md.

    uv run python results/representation/gen.py

Same contract as the other generators here -- numbers read out of `runs/`, never
transcribed, and only the block between the GENERATED markers is rewritten. The prose above
it is hand-written and survives regeneration.

Three measurements over one directory, one subtree each under `runs/representation/`:
geometry (phase 0), label efficiency and kNN (phase 2). They share a README because they
share a feature extraction and answer one question between them -- what the representation
is, before any of it is fit -- and each writes its own CSV rather than one wide join,
because their rows are not the same rows: geometry has one per cell, the curve five, kNN
one per k.
"""

import json
from pathlib import Path

import polars as pl

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
RUNS = ROOT / "runs" / "representation" / "geometry"
RUNS_LABEL_EFFICIENCY = ROOT / "runs" / "representation" / "label_efficiency"
RUNS_KNN = ROOT / "runs" / "representation" / "knn"

#: The floor both phase-2 tasks publish beside themselves, filed under its own cell name.
FLOOR = "moments"

# The 3x3 the evaluation plan scores. `pv` exists in the pretraining tree and is not part of
# any table here -- it is excluded at the report, not at the runner, so bringing it back is
# an edit to this line and no reruns.
AXIS = ["p", "pk", "pkd"]

BEGIN = "<!-- GENERATED by gen.py -- do not edit below this line -->"
END = "<!-- /GENERATED -->"


def collect() -> pl.DataFrame:
    """One row per measured cell.

    rglob rather than a fixed-depth glob, same as the probe generator: replicates nest an
    extra `seed<N>` segment and a fixed depth would find the canonical runs and silently
    skip every replicate.
    """

    rows = []
    for metrics_path in sorted(RUNS.rglob("in_*/metrics.json")):
        cell = metrics_path.parent
        parts = cell.relative_to(RUNS).parts
        if len(parts) < 3:
            continue
        payload = json.loads(metrics_path.read_text())
        name = cell.name
        rows.append(
            {
                "corpus": parts[0],
                "arch": parts[1],
                "replicate": "/".join(parts[2:-1]),
                "cell": name,
                "input": name.removeprefix("in_").split("__")[0],
                "loss": name.split("__loss_")[1] if "__loss_" in name else None,
                "n": payload["n"],
                "d": payload["d"],
                "pool": payload.get("pool"),
                **payload["metrics"],
            }
        )
    return pl.DataFrame(rows)


def tables(df: pl.DataFrame) -> str:
    """Participation ratio as the 3x3 the fine-tune table uses, meaned over replicates."""

    if df.is_empty():
        return "*No geometry runs found under `runs/representation/geometry/`.*"

    parts = [
        f"*{len(df)} cells, {df['n'][0]} validation windows, d = {df['d'][0]} "
        f"(`{df['pool'][0]}` pooling). Regenerate with `gen.py`.*",
        "",
        "## Participation ratio",
        "",
    ]
    for (corpus, arch), group in sorted(df.group_by("corpus", "arch")):
        stats = group.group_by("input", "loss").agg(
            pl.col("participation_ratio").mean(),
            pl.col("participation_ratio").std().alias("sd"),
            pl.len().alias("seeds"),
        )
        grid = {(r["input"], r["loss"]): r for r in stats.iter_rows(named=True)}
        # Pooled over cells, the same way the probe report pools its seed spread: one
        # cell's three seeds estimate sigma badly, nine cells' worth of them does not.
        spread = [r["sd"] for r in grid.values() if r["sd"] is not None]
        pooled = sum(spread) / len(spread) if spread else None
        parts += [
            f"**{corpus} / {arch}** -- rows are the encoder's input channels, columns its "
            f"loss channels.",
            "",
            "| input \\ loss | " + " | ".join(f"`{loss}`" for loss in AXIS) + " |",
            "| :--- | " + " | ".join("---:" for _ in AXIS) + " |",
        ]
        for channels in AXIS:
            cells = []
            for loss in AXIS:
                row = grid.get((channels, loss))
                if row is None:
                    cells.append("--")
                elif row["sd"] is None:
                    cells.append(f"{row['participation_ratio']:.2f}")
                else:
                    cells.append(f"{row['participation_ratio']:.2f} ±{row['sd']:.2f}")
            parts += ["| `" + channels + "` | " + " | ".join(cells) + " |"]
        parts += [""]
        if pooled is not None:
            seeds = sorted({r["seeds"] for r in grid.values()})
            parts += [
                f"*± is the sd over pretraining replicates "
                f"({'/'.join(str(s) for s in seeds)} per cell). Pooled over cells it is "
                f"{pooled:.2f}, so a difference below ~{2 * pooled:.1f} is inside seed noise. "
                f"Dimensionality and variance are not interchangeable: read this beside "
                f"`total_variance` in `metrics.csv`, which moves the other way.*",
                "",
            ]

    return "\n".join(parts)


def cka_tables() -> str:
    """Cross-cell CKA against the cross-seed floor, one block per matrix that has both.

    Printed as a pair on purpose: a cross-cell CKA alone says nothing, because the question
    is always whether two cells differ by more than two seeds of one cell do.
    """

    parts = []
    for metrics_path in sorted(RUNS.rglob("cka/metrics.json")):
        metrics = json.loads(metrics_path.read_text())["metrics"]
        if not metrics:
            continue
        where = metrics_path.parent.parent.relative_to(RUNS)
        parts += [
            f"**{where}**",
            "",
            "| pairs | mean | sd | n |",
            "| :--- | ---: | ---: | ---: |",
        ]
        for prefix, label in (("cross_cell", "different cell, same seed"), ("cross_seed", "same cell, different seed")):
            if f"{prefix}_mean" in metrics:
                parts += [
                    f"| {label} | {metrics[f'{prefix}_mean']:.4f} | "
                    f"{metrics[f'{prefix}_sd']:.4f} | {metrics[f'{prefix}_n']} |"
                ]
        parts += [""]

    if not parts:
        return ""
    return "\n".join(["## Linear CKA", "", *parts])


def _cells(root: Path):
    """``(payload, meta)`` for every scored directory under one measurement's subtree.

    `in_*` cells and the `moments` floor, which is not a matrix cell and has no input or
    loss axis but belongs in the same table by the standing rule -- collected here so the
    floor is read out of `runs/` like everything else instead of transcribed into prose.

    rglob rather than a fixed-depth glob, same as :func:`collect`: replicates nest an extra
    `seed<N>` segment, and the floor does not, so one fixed depth cannot see both.
    """

    for metrics_path in sorted(root.rglob("*/metrics.json")):
        cell = metrics_path.parent
        parts = cell.relative_to(root).parts
        if len(parts) < 3 or (cell.name != FLOOR and not cell.name.startswith("in_")):
            continue
        yield json.loads(metrics_path.read_text()), {
            "corpus": parts[0],
            "arch": parts[1],
            "replicate": "/".join(parts[2:-1]),
            "cell": cell.name,
        }


def collect_label_efficiency() -> pl.DataFrame:
    """One row per (cell, fraction). Long, not wide: five refits are five measurements."""

    rows = []
    for payload, meta in _cells(RUNS_LABEL_EFFICIENCY):
        for fraction in payload["fractions"]:
            rows.append(
                meta
                | {
                    "fraction": fraction["fraction"],
                    "samples": fraction["samples"],
                    "windows": fraction["windows"],
                    "weight_decay": fraction["weight_decay"],
                    # Carried per row so the CSV shows the optimum moving with training set
                    # size -- the reason the sweep is redone at every fraction.
                    **fraction["metrics"],
                    "labels_scored": payload["labels"]["scored"],
                    # The identity of the scored vocabulary, not just its size. Two runs
                    # averaging 18 labels each are only comparable if they are the *same*
                    # 18, and this is the column that proves it.
                    "label_key": ",".join(str(i) for i in payload["labels"]["indices"]),
                }
            )
    return pl.DataFrame(rows)


def collect_knn() -> pl.DataFrame:
    """One row per (cell, k). The whole sweep, not the argmax -- k is a column, not a choice."""

    rows = []
    for payload, meta in _cells(RUNS_KNN):
        for k, metrics in payload["sweep"].items():
            rows.append(meta | {"k": int(k), **metrics})
    return pl.DataFrame(rows)


def pivot(
    df: pl.DataFrame, column: str, heading: str, note: str, header=str, ratio: str = ""
) -> str:
    """Rows are cells, columns are ``column``, values are macro mAP meaned over replicates.

    One helper for both phase-2 tables because they are the same table: a cell per row, a
    sweep across the columns, and the floor as the last row rather than a separate block --
    a baseline printed somewhere else is a baseline nobody reads against the number.
    """

    if df.is_empty():
        return ""

    parts = [f"## {heading}", ""]
    for (corpus, arch), group in sorted(df.group_by("corpus", "arch")):
        averaged = group.group_by("cell", column).agg(pl.col("macro_map").mean())
        values = {(row["cell"], row[column]): row["macro_map"] for row in averaged.iter_rows(named=True)}
        levels = sorted({key[1] for key in values})
        # The floor sorts last wherever it appears, so the table reads top-down as
        # "the cells, then what they have to beat".
        names = sorted({key[0] for key in values}, key=lambda name: (name == FLOOR, name))
        # Over the cells only: the floor is measured once per matrix and would otherwise
        # add its empty replicate to the count and understate nothing but confuse everyone.
        replicates = max(1, group.filter(pl.col("cell") != FLOOR)["replicate"].n_unique())

        headers = [header(level) for level in levels]
        parts += [
            f"**{corpus} / {arch}** -- {note} Mean over {replicates} pretraining seed(s).",
            "",
            "| cell | " + " | ".join(headers) + (f" | {ratio} |" if ratio else " |"),
            "| :--- | " + " | ".join("---:" for _ in headers) + (" | ---: |" if ratio else " |"),
        ]
        for name in names:
            row = [values.get((name, level)) for level in levels]
            line = [f"`{name}`" + (" (floor)" if name == FLOOR else "")]
            line += ["--" if value is None else f"{value:.4f}" for value in row]
            if ratio:
                first, last = row[0], row[-1]
                line += ["--" if not first or not last else f"{first / last:.2f}"]
            parts += ["| " + " | ".join(line) + " |"]
        parts += [""]

    return "\n".join(parts)


def label_efficiency_tables(df: pl.DataFrame) -> str:
    """The curve, plus the one line that says whether it is a curve at all.

    Every fraction of every run has to have scored the *same* labels. If it did not, the
    points are macro averages over different vocabularies and the table is five metrics
    wearing one name, so that is said loudly here rather than left for a reader to notice.
    """

    if df.is_empty():
        return ""

    keys = df["label_key"].unique()
    scored = df["labels_scored"].unique().to_list()
    if len(keys) == 1:
        note = (
            f"macro mAP at each fraction of the labelled training set, every point scored on "
            f"the same {scored[0]} of 60 labels (those with support at 5%)."
        )
    else:
        note = (
            f"**INCONSISTENT: {len(keys)} different label sets across these runs "
            f"({scored} labels) -- the columns are not one metric and must not be compared.**"
        )
    return pivot(df, "fraction", "Label efficiency", note, header="{:.0%}".format, ratio="5% / 100%")


def splice(readme: Path, generated: str) -> None:
    block = f"{BEGIN}\n\n{generated}\n{END}"
    if readme.exists() and BEGIN in readme.read_text():
        text = readme.read_text()
        head, _, rest = text.partition(BEGIN)
        _, _, tail = rest.partition(END)
        readme.write_text(head + block + tail)
    else:
        readme.write_text(f"# Representation geometry\n\n{block}\n")


def in_scope(df: pl.DataFrame) -> pl.DataFrame:
    """The 3x3 plus the floor. `pv` and `moments` both fail an `AXIS` test, for opposite
    reasons, so the floor is exempted explicitly rather than by widening AXIS."""

    if df.is_empty():
        return df
    cell = pl.col("cell")
    axis = "|".join(AXIS)
    return df.filter((cell == FLOOR) | cell.str.contains(rf"^in_({axis})__loss_({axis})$"))


def main() -> None:
    df = collect()
    if not df.is_empty():
        df = df.filter(pl.col("loss").is_in(AXIS) & pl.col("input").is_in(AXIS)).sort(
            "corpus", "arch", "replicate", "input", "loss"
        )
        df.write_csv(HERE / "metrics.csv")

    efficiency = in_scope(collect_label_efficiency())
    knn = in_scope(collect_knn())
    for frame, name in ((efficiency, "label_efficiency.csv"), (knn, "knn.csv")):
        if not frame.is_empty():
            frame.sort("corpus", "arch", "replicate", "cell").write_csv(HERE / name)

    splice(
        HERE / "README.md",
        "\n".join(
            filter(
                None,
                [
                    tables(df),
                    cka_tables(),
                    label_efficiency_tables(efficiency),
                    pivot(
                        knn,
                        "k",
                        "kNN retrieval",
                        "macro mAP, no head fit, neighbour count across the columns.",
                        header="k={}".format,
                    ),
                ],
            )
        ),
    )
    print(
        f"{len(df)} geometry cells, {efficiency['cell'].n_unique() if not efficiency.is_empty() else 0} "
        f"label-efficiency cells, {knn['cell'].n_unique() if not knn.is_empty() else 0} kNN cells "
        f"-> {HERE}"
    )


if __name__ == "__main__":
    main()
