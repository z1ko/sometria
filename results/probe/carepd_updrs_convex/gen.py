#!/usr/bin/env python
"""Summarize the CARE-PD protocol runs into metrics.csv and the tables in README.md.

    uv run python results/probe/carepd_updrs_convex/gen.py

Sibling of `results/probe/babel_60_convex/gen.py` and the same contract -- numbers are
read out of the runs, never transcribed, and only the block between the GENERATED markers
is rewritten so hand-written prose survives regeneration. What differs is the shape of the
thing being summarized. BABEL-60 is one split scored over a 3x3 input-by-loss matrix;
CARE-PD is two cells scored over 126 split sets that group into 20 experiments across
three protocols, so the axis worth tabulating is the protocol, not the matrix.

Three numbers are reported per experiment and they are not interchangeable:

``macro_f1_0123``  the paper's metric, and the only one comparable to published work.
``macro_f1_012``   the same model with the rare score 3 dropped from the *average* only.
                   Samples carrying it stay in, so a true-3 take predicted as 2 still
                   counts against class 2 (paper S4.3). Always the higher of the two, and
                   the gap is a measure of how much of the score class 3 is eating.
``macro_map``      ours, threshold-free, kept because macro F1 depends on where argmax
                   happens to fall and a ranking metric does not.

Everything is the *pooled* figure: every fold's held-out predictions scored once as one
set, not the mean of per-fold scores. `probe_convex_protocol.py` explains why at length --
briefly, a LOSO fold holds out one patient who often walks at a single severity, which
inflates mAP to 1.0 by construction and deflates macro F1 by dividing across classes that
patient never walks at. The per-fold mean and its spread are still written to the CSV,
because that spread is real between-subject variability.

`reference.json` holds the paper's numbers and is the one file here that is transcribed
rather than measured; it carries its own caveats. The majority-class floor is computed
from the catalog rather than stored, so it cannot drift away from the splits it describes.
"""

import json
from collections import Counter
from pathlib import Path
from statistics import NormalDist

import polars as pl
from omegaconf import OmegaConf

BENCHMARK = Path(__file__).resolve().parent.name
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
RUNS = ROOT / "runs" / "probe" / BENCHMARK / "protocols"
PROCESSED = ROOT / "data" / "processed"

COHORTS = ["3DGait", "BMCLab", "PD-GaM", "T-SDU-PD"]
METRICS = ["macro_f1_0123", "macro_f1_012", "macro_map", "micro_map"]
REPORTED = ["macro_f1_0123", "macro_f1_012", "macro_map"]
PRIMARY = "macro_f1_0123"

TITLES = {
    "macro_f1_0123": "Macro F1 (0-3)",
    "macro_f1_012": "Macro F1 (0-2)",
    "macro_map": "Macro mAP",
}
PROTOCOL_TITLES = {
    "loso": "Within-site, leave-one-subject-out",
    "lodo": "Leave-one-dataset-out",
    "cross": "Cross-dataset",
}

BEGIN = "<!-- GENERATED by gen.py -- do not edit below this line -->"
END = "<!-- /GENERATED -->"


def classify(group: str) -> dict:
    """Which protocol a split-set family belongs to, and what it trains and tests on."""

    if group.startswith("carepd_cross_"):
        source, target = group.removeprefix("carepd_cross_").split("_to_")
        return {"protocol": "cross", "source": source, "target": target}
    if group.startswith("carepd_lodo_"):
        target = group.removeprefix("carepd_lodo_")
        return {"protocol": "lodo", "source": "the other three", "target": target}
    if group.endswith("_loso"):
        cohort = group.removeprefix("carepd_").removesuffix("_loso")
        return {"protocol": "loso", "source": cohort, "target": cohort}
    return {"protocol": "other", "source": None, "target": group}


def _relative(path: str | None) -> str | None:
    """Repo-relative form of a recorded path, whichever way it was written."""

    if not path:
        return None
    candidate = Path(path)
    if not candidate.is_absolute():
        return str(candidate)
    try:
        return str(candidate.relative_to(ROOT))
    except ValueError:
        return str(candidate)


def collect() -> pl.DataFrame:
    """One row per (run, protocol group), with the provenance its own config.yaml records."""

    rows = []
    for metrics_path in sorted(RUNS.rglob("in_*__loss_*/metrics.json")):
        run = metrics_path.parent
        parts = run.relative_to(RUNS).parts
        if len(parts) < 4:
            continue
        corpus, arch, seed, cell = parts[0], parts[1], parts[2], parts[3]
        payload = json.loads(metrics_path.read_text())

        config_path = run / "config.yaml"
        config = OmegaConf.load(config_path) if config_path.exists() else None

        for group, stats in payload["summary"].items():
            pooled, per_fold = stats["pooled"], stats["per_fold"]
            rows.append(
                {
                    "corpus": corpus,
                    "arch": arch,
                    "seed": seed,
                    "cell": cell,
                    "input": cell.removeprefix("in_").split("__")[0],
                    "loss": cell.split("__loss_")[1],
                    "group": group,
                    **classify(group),
                    "folds": stats["folds"],
                    **{m: pooled.get(m) for m in METRICS},
                    # Kept beside the pooled figure rather than instead of it: the level is
                    # an artefact on single-subject folds, the spread is not.
                    **{f"per_fold_{m}": per_fold.get(m, {}).get("mean") for m in REPORTED},
                    **{f"per_fold_sd_{m}": per_fold.get(m, {}).get("sd") for m in REPORTED},
                    "weight_decay": payload.get("weight_decay"),
                    "tuned_on": payload.get("tuned_on"),
                    "selected_on": payload.get("selected_on"),
                    "tuned_per_fold": payload.get("weight_decay_tuned_per_fold"),
                    "normalization": (
                        Path(config.dataloader.normalization).name if config else None
                    ),
                    "checkpoint": _relative(config.model.get("checkpoint")) if config else None,
                }
            )

    if not rows:
        raise FileNotFoundError(f"no metrics.json under {RUNS}")
    return pl.DataFrame(rows)


def macro_f1(true: list[str], predicted: list[str], labels: list[str]) -> float:
    """Unweighted mean F1 over ``labels``. A class with no support scores 0, as in the paper."""

    scores = []
    for label in labels:
        tp = sum(t == label and p == label for t, p in zip(true, predicted))
        fp = sum(p == label and t != label for t, p in zip(true, predicted))
        fn = sum(p != label and t == label for t, p in zip(true, predicted))
        denominator = 2 * tp + fp + fn
        scores.append(0.0 if denominator == 0 else 2 * tp / denominator)
    return sum(scores) / len(scores)


def majority_floor() -> dict[str, float]:
    """Macro F1 of predicting each split's training-majority class, per protocol group.

    The floor a probe has to clear, and the reason it is computed here rather than written
    into a JSON: it is a property of the splits, so a change to them should move it rather
    than silently leave a stale number in a table. Returns ``{}`` when the processed data
    is not present, since the runs can be summarized without it.
    """

    from sometria.catalog import load_annotations, load_splits

    try:
        annotations = load_annotations(PROCESSED).filter(pl.col("ontology") == "updrs_gait")
        splits = load_splits(PROCESSED).filter(pl.col("split_set").str.starts_with("carepd_"))
    except FileNotFoundError:
        return {}
    if annotations.is_empty() or splits.is_empty():
        return {}

    label_of = dict(zip(annotations["sample_id"], annotations["label"]))
    resolved = splits.filter(pl.col("sample_id").is_in(list(label_of)))

    per_split: dict[str, tuple[list[str], str]] = {}
    for name, rows in resolved.group_by("split_set"):
        name = name[0]
        train = [label_of[i] for i in rows.filter(pl.col("split") == "train")["sample_id"]]
        held = [label_of[i] for i in rows.filter(pl.col("split") == "eval")["sample_id"]]
        if train and held:
            per_split[name] = (held, Counter(train).most_common(1)[0][0])

    floors: dict[str, list[tuple[list[str], str]]] = {}
    for name, entry in per_split.items():
        group = name.rpartition("_")[0] if name.rpartition("_")[2].isdigit() else name
        floors.setdefault(group, []).append(entry)

    # Pooled the same way the probe's own number is, so the two are comparable.
    return {
        group: macro_f1(
            [t for held, _ in entries for t in held],
            [m for held, m in entries for _ in held],
            ["0", "1", "2", "3"],
        )
        for group, entries in floors.items()
    }


def cell_columns(df: pl.DataFrame) -> list[str]:
    return sorted(df["cell"].unique())


def protocol_table(df: pl.DataFrame, protocol: str, floors: dict, reference: dict) -> str:
    """Cohorts down, cells across; mean over seeds with the sample sd beside it."""

    cells = cell_columns(df)
    subset = df.filter(pl.col("protocol") == protocol)
    paper = reference.get({"loso": "within_dataset_loso", "lodo": "lodo"}.get(protocol, ""), {})

    header = ["target", "folds", "majority floor", *(f"`{c}`" for c in cells)]
    if paper:
        header.append("paper")
    lines = [
        "| " + " | ".join(header) + " |",
        "| :--- | ---: | ---: |" + " ---: |" * len(cells) + (" :---: |" if paper else ""),
    ]

    for target in COHORTS:
        rows = subset.filter(pl.col("target") == target)
        if rows.is_empty():
            continue
        group = rows["group"][0]
        floor = floors.get(group)
        cell_text = []
        for cell in cells:
            values = rows.filter(pl.col("cell") == cell)[PRIMARY].to_list()
            values = [v for v in values if v is not None]
            if not values:
                cell_text.append("--")
                continue
            mean = sum(values) / len(values)
            if len(values) > 1:
                sd = (sum((v - mean) ** 2 for v in values) / (len(values) - 1)) ** 0.5
                cell_text.append(f"{mean:.4f} ±{sd:.4f}")
            else:
                cell_text.append(f"{mean:.4f}")
        line = (
            f"| **{target}** | {rows['folds'][0]} | "
            f"{'--' if floor is None else f'{floor:.4f}'} | " + " | ".join(cell_text)
        )
        if paper:
            entry = paper.get(target, {})
            if "mean" in entry:
                line += f" | {entry['mean']:.3f} ±{entry['sd']:.3f}"
            elif "low" in entry:
                line += f" | {entry['low']:.2f}–{entry['high']:.2f}"
            else:
                line += " | --"
        lines.append(line + " |")
    return "\n".join(lines)


def cross_matrix(df: pl.DataFrame, cell: str) -> str:
    """Source-by-target grid for one cell, averaged over seeds. Diagonal is not run."""

    subset = df.filter((pl.col("protocol") == "cross") & (pl.col("cell") == cell))
    values = {
        (r["source"], r["target"]): r[PRIMARY]
        for r in subset.group_by("source", "target").agg(pl.col(PRIMARY).mean()).iter_rows(named=True)
    }

    lines = [
        "| train \\ test | " + " | ".join(COHORTS) + " | mean |",
        "| :--- |" + " ---: |" * (len(COHORTS) + 1),
    ]
    for source in COHORTS:
        cells, present = [], []
        for target in COHORTS:
            if source == target:
                cells.append("·")
                continue
            value = values.get((source, target))
            cells.append("--" if value is None else f"{value:.4f}")
            if value is not None:
                present.append(value)
        mean = f"**{sum(present) / len(present):.4f}**" if present else "--"
        lines.append(f"| **{source}** | " + " | ".join(cells) + f" | {mean} |")

    footer = []
    for target in COHORTS:
        column = [values[(s, target)] for s in COHORTS if (s, target) in values]
        footer.append(f"**{sum(column) / len(column):.4f}**" if column else "--")
    lines.append("| **mean** | " + " | ".join(footer) + " | |")
    return "\n".join(lines)


def cell_delta(df: pl.DataFrame) -> list[str]:
    """Paired comparison of the two cells, one pair per (group, seed).

    Paired because both cells are probed from the same pretraining seed on the same folds,
    so the seed-to-seed variation that dominates either column cancels. Treating them as
    independent samples would divide by a spread that is mostly shared and understate the
    evidence -- or, here, overstate how uncertain a null result is.
    """

    cells = cell_columns(df)
    if len(cells) != 2:
        return []
    base, other = cells

    keyed = {
        (r["group"], r["seed"], r["cell"]): r[PRIMARY]
        for r in df.iter_rows(named=True)
        if r[PRIMARY] is not None
    }
    pairs = [
        (group, seed, keyed[(group, seed, other)] - keyed[(group, seed, base)])
        for group, seed, cell in keyed
        if cell == base and (group, seed, other) in keyed
    ]
    if not pairs:
        return []

    deltas = [d for _, _, d in pairs]
    n = len(deltas)
    mean = sum(deltas) / n
    sd = (sum((d - mean) ** 2 for d in deltas) / (n - 1)) ** 0.5 if n > 1 else 0.0
    se = sd / n**0.5 if n > 1 else None
    wins = sum(d > 0 for d in deltas)
    threshold = NormalDist().inv_cdf(0.975)

    verdict = (
        "no measurable difference"
        if se is None or abs(mean / se) < threshold
        else f"`{other}` differs from `{base}`"
    )
    return [
        f"## Cell comparison, `{other}` − `{base}`",
        "",
        f"| pairs | mean Δ | sd | SE | t | wins | verdict |",
        "| ---: | ---: | ---: | ---: | ---: | ---: | :--- |",
        f"| {n} | {mean:+.4f} | {sd:.4f} | "
        + ("--" if se is None else f"{se:.4f}")
        + " | "
        + ("--" if se is None else f"{mean / se:+.2f}")
        + f" | {wins}/{n} | {verdict} |",
        "",
        f"*Paired on (protocol group, seed). |t| > {threshold:.2f} would be significant at "
        "0.05 two-sided.*",
        "",
    ]


def seed_spread(df: pl.DataFrame) -> list[str]:
    """Seed-to-seed sd of the pooled figure, pooled over the groups of each protocol.

    The number every claim in this folder has to clear. Pooled over groups because three
    seeds give a per-group sd two degrees of freedom, which is mostly luck.
    """

    per_group = (
        df.group_by("protocol", "cell", "group")
        .agg(pl.len().alias("n"), *[pl.col(m).std().alias(f"sd_{m}") for m in REPORTED])
        .filter(pl.col("n") > 1)
    )
    if per_group.is_empty():
        return []

    spread = (
        per_group.group_by("protocol")
        .agg(
            pl.col("n").max().alias("seeds"),
            pl.len().alias("group_cells"),
            *[pl.col(f"sd_{m}").mean().alias(f"sd_{m}") for m in REPORTED],
        )
        .sort("protocol")
    )
    return [
        "## Seed spread",
        "",
        "| protocol | seeds | group×cells | " + " | ".join(f"sd {TITLES[m]}" for m in REPORTED) + " |",
        "| :--- | ---: | ---: |" + " ---: |" * len(REPORTED),
        *(
            f"| {PROTOCOL_TITLES.get(r['protocol'], r['protocol'])} | {r['seeds']} | "
            f"{r['group_cells']} | "
            + " | ".join(f"{r[f'sd_{m}']:.4f}" for m in REPORTED)
            + " |"
            for r in spread.iter_rows(named=True)
        ),
        "",
    ]


def metric_variants(df: pl.DataFrame) -> list[str]:
    """The same runs under all three reported metrics, so the choice of metric is visible."""

    lines = [
        "## The three metrics, side by side",
        "",
        "| protocol | target | " + " | ".join(TITLES[m] for m in REPORTED) + " | 0-2 ÷ 0-3 |",
        "| :--- | :--- |" + " ---: |" * (len(REPORTED) + 1),
    ]
    for protocol in ("loso", "lodo"):
        for target in COHORTS:
            rows = df.filter((pl.col("protocol") == protocol) & (pl.col("target") == target))
            if rows.is_empty():
                continue
            means = {m: rows[m].mean() for m in REPORTED}
            ratio = (
                means["macro_f1_012"] / means["macro_f1_0123"]
                if means.get("macro_f1_0123")
                else None
            )
            lines.append(
                f"| {protocol} | {target} | "
                + " | ".join(f"{means[m]:.4f}" for m in REPORTED)
                + f" | {'--' if ratio is None else f'{ratio:.3f}'} |"
            )
    return lines + [""]


def tables(df: pl.DataFrame) -> str:
    floors = majority_floor()
    reference = json.loads((HERE / "reference.json").read_text())
    cells = cell_columns(df)
    runs = df.select("corpus", "arch", "seed", "cell").unique().height
    seeds = sorted(df["seed"].unique())

    parts = [
        f"*{runs} runs ({len(cells)} cells × {len(seeds)} seeds) over "
        f"{df['group'].n_unique()} protocol groups. Pooled figures throughout. "
        "Regenerate with `gen.py`.*",
        "",
        f"Corpus `{'`, `'.join(sorted(df['corpus'].unique()))}`, "
        f"arch `{'`, `'.join(sorted(df['arch'].unique()))}`, seeds "
        f"{', '.join(s.removeprefix('seed') for s in seeds)}. "
        f"Primary metric **{TITLES[PRIMARY]}**, the paper's.",
        "",
    ]

    for protocol in ("loso", "lodo"):
        if df.filter(pl.col("protocol") == protocol).is_empty():
            continue
        parts += [
            f"## {PROTOCOL_TITLES[protocol]}",
            "",
            protocol_table(df, protocol, floors, reference),
            "",
        ]

    if not df.filter(pl.col("protocol") == "cross").is_empty():
        parts += [f"## {PROTOCOL_TITLES['cross']}", ""]
        for cell in cells:
            parts += [f"### `{cell}`", "", cross_matrix(df, cell), ""]
        paper = reference.get("cross_dataset", {})
        if paper:
            measured = (
                df.filter(pl.col("protocol") == "cross")
                .group_by("target")
                .agg(pl.col(PRIMARY).mean())
            )
            got = {r["target"]: r[PRIMARY] for r in measured.iter_rows(named=True)}
            parts += [
                "| by target | " + " | ".join(COHORTS) + " |",
                "| :--- |" + " ---: |" * len(COHORTS),
                "| ours | " + " | ".join(f"{got[c]:.4f}" if c in got else "--" for c in COHORTS) + " |",
                "| paper | "
                + " | ".join(
                    f"{paper[c]['mean']:.3f} ±{paper[c]['sd']:.3f}" if c in paper else "--"
                    for c in COHORTS
                )
                + " |",
                "",
            ]

    parts += cell_delta(df)
    parts += seed_spread(df)
    parts += metric_variants(df)

    parts += ["## Reference points", "", f"*{reference['caveat']}*", ""]
    parts += [f"- **Source** -- {reference['source']}", ""]

    parts += ["## Provenance", ""]
    provenance = (
        df.group_by("corpus", "arch", "cell", "normalization", "tuned_on", "selected_on")
        .agg(pl.col("seed").unique().sort().str.join(", ").alias("seeds"))
        .sort("corpus", "arch", "cell")
    )
    parts += [
        "| corpus | arch | cell | seeds | normalization | weight decay tuned on | selected by |",
        "| :--- | :--- | :--- | :--- | :--- | :--- | :--- |",
        *(
            f"| {r['corpus']} | {r['arch']} | `{r['cell']}` | {r['seeds']} | "
            f"`{r['normalization']}` | `{r['tuned_on']}` | `{r['selected_on']}` |"
            for r in provenance.iter_rows(named=True)
        ),
        "",
    ]
    return "\n".join(parts)


def splice(readme: Path, generated: str) -> None:
    """Replace the generated block, leaving hand-written prose untouched."""

    block = f"{BEGIN}\n\n{generated}\n{END}"
    if readme.exists() and BEGIN in readme.read_text():
        text = readme.read_text()
        head, _, rest = text.partition(BEGIN)
        _, _, tail = rest.partition(END)
        readme.write_text(head + block + tail)
    else:
        readme.write_text(f"# {BENCHMARK}\n\n{block}\n")


def main() -> None:
    df = collect().sort("corpus", "arch", "protocol", "target", "cell", "seed")
    df.write_csv(HERE / "metrics.csv")
    splice(HERE / "README.md", tables(df))
    print(f"{len(df)} rows -> {HERE / 'metrics.csv'} and README.md")


if __name__ == "__main__":
    main()
