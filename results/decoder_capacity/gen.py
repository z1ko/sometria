#!/usr/bin/env python
"""Summarize the decoder-capacity ablation into metrics.csv and the tables in README.md.

    uv run python results/decoder_capacity/gen.py
    uv run python results/decoder_capacity/gen.py --measure    # refresh evidence.json (GPU)

Same contract as the other generators here -- numbers read, never transcribed, and only
the block between the GENERATED markers is rewritten.

The one thing this computes rather than reads is the decoder's share of the model's work,
and it is derived from the architecture configs rather than typed in. That matters because
the number is not obvious: `medium` looks like a modest decoder at dec_depth 3 against
enc_depth 6, and is in fact 8.5x the encoder's FLOPs, because at mask_ratio 0.90 the
encoder sees 128 tokens while the decoder always reconstructs all 1290. Typing "8.5x" into
a table would leave nothing to catch a config change that moves it.

`evidence.json` holds two supporting measurements that do not come from `runs/`: the CKA
between checkpoints, and how much of tau is linearly recoverable from the other channels.
Both need a GPU and a few minutes, so they are cached rather than recomputed on every
regeneration -- `--measure` refreshes them, and each records the command that produced it.
"""

import argparse
import json
import re
from pathlib import Path

import polars as pl
import yaml
from scipy.stats import t as student_t
from omegaconf import OmegaConf

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
BENCHMARK = "babel_60_convex"
RUNS = ROOT / "runs" / "probe" / BENCHMARK

# The two cells whose difference the ablation is about: same encoder input, one extra
# reconstruction target. Everything else in the matrix is held out of this table.
# One corpus only. `medium` has been probed on two of them and the weakened rungs on one,
# so pooling would compare a three-seed amass_clean average against a mixture -- which is
# how the first version of this table reported sigma 0.0073 instead of 0.0011 and turned a
# 10-sigma result into a 1.5-sigma one.
CORPUS = "amass_clean"
AXIS = ["p", "pk", "pkd"]
CELLS = [f"in_{i}__loss_{l}" for i in AXIS for l in AXIS]
ARCHES = ["medium", "medium_thindec", "medium_tinydec"]
BASELINE = "medium"
METRIC = "macro_map"

BEGIN = "<!-- GENERATED by gen.py -- do not edit below this line -->"
END = "<!-- /GENERATED -->"


def block_flops(tokens: int, width: int, mlp_ratio: int) -> int:
    """Rough FLOPs of one transformer block: projections, attention scores, feed-forward.

    Attention is quadratic in the token count and only linear in width, which is why
    halving `dec_dim` does not halve the decoder's cost -- and why the decoder, running
    over ten times as many tokens as the encoder, is so much more expensive than its
    depth suggests.
    """

    return (
        4 * tokens * width * width          # q, k, v, output projections
        + 2 * tokens * tokens * width       # scores and the weighted sum
        + 2 * tokens * width * (mlp_ratio * width)
    )


def capacity() -> dict[str, dict]:
    """Decoder-to-encoder FLOP ratio for each architecture, read out of its config."""

    base = OmegaConf.load(ROOT / "config" / "pretrain_mae.yaml").model
    tokens = base.num_dofs * (base.num_frames // base.num_frames_in_patch)
    seen = int(tokens * (1 - base.mask_ratio))

    out = {}
    for arch in ARCHES:
        path = ROOT / "config" / "mae" / f"{arch}.yaml"
        if not path.exists():
            continue
        model = {**OmegaConf.to_container(base), **yaml.safe_load(path.read_text())["model"]}
        width = model.get("dec_dim") or model["dim"]
        encoder = block_flops(seen, model["dim"], model["mlp_ratio"]) * model["enc_depth"]
        decoder = block_flops(tokens, width, model["mlp_ratio"]) * model["dec_depth"]
        out[arch] = {
            "enc_depth": model["enc_depth"],
            "dec_depth": model["dec_depth"],
            "dec_dim": width,
            "encoder_gflops": encoder / 1e9,
            "decoder_gflops": decoder / 1e9,
            "ratio": decoder / encoder,
        }
    return out


def collect() -> pl.DataFrame:
    """One row per (arch, seed, cell) for the two cells the ablation compares."""

    rows = []
    for arch in ARCHES:
        # Anchored, because `medium_*ep` also matches `medium_thindec_100ep` and
        # `medium_tinydec_100ep` -- a glob whose leading name is a prefix of its siblings
        # swallows them. First version of this table folded all three rungs into the
        # `medium` row and reported it as five seeds.
        pattern = re.compile(rf"^{re.escape(arch)}_\d+ep$")
        for metrics_path in sorted(RUNS.rglob("in_*__loss_*/metrics.json")):
            cell = metrics_path.parent.name
            if cell not in CELLS:
                continue
            parts = metrics_path.parent.relative_to(RUNS).parts
            if parts[0] != CORPUS or len(parts) < 2 or not pattern.match(parts[1]):
                continue
            payload = json.loads(metrics_path.read_text())
            rows.append(
                {
                    "corpus": parts[0],
                    "arch": arch,
                    "seed": parts[2] if len(parts) > 3 else "",
                    "cell": cell,
                    "input": cell.removeprefix("in_").split("__")[0],
                    "loss": cell.split("__loss_")[1],
                    "weight_decay": payload["weight_decay"],
                    METRIC: payload["metrics"][METRIC],
                }
            )
    if not rows:
        raise FileNotFoundError(f"no {CELLS} runs for {ARCHES} under {RUNS}")
    return pl.DataFrame(rows)


def paired(df: pl.DataFrame, arch: str, inp: str, a: str, b: str) -> list[float]:
    """Per-seed differences between two cells of one arch, in a fixed seed order.

    Paired, because both cells come from the same pretraining seed: the seed-to-seed
    variation that dominates either column is shared and cancels. Treating them as
    independent samples divides by a spread that is mostly common, and here that is not a
    rounding difference -- unpaired it calls the medium in_pk gap 0.8 sigma, paired it is
    t = 10, a real effect that happens to be tiny.
    """

    def at(loss):
        rows = df.filter(
            (pl.col("arch") == arch) & (pl.col("input") == inp) & (pl.col("loss") == loss)
        ).sort("seed")
        return dict(zip(rows["seed"], rows[METRIC]))

    left, right = at(b), at(a)
    return [left[s] - right[s] for s in sorted(set(left) & set(right))]


def stats(values: list[float]) -> tuple[float, float | None, float | None]:
    """Mean, sample sd and t of a set of paired differences."""

    if not values:
        return 0.0, None, None
    mean = sum(values) / len(values)
    if len(values) < 2:
        return mean, None, None
    sd = (sum((v - mean) ** 2 for v in values) / (len(values) - 1)) ** 0.5
    se = sd / len(values) ** 0.5
    return mean, sd, (mean / se if se else None)


def significance(t: float | None, n: int, tests: int = 1) -> tuple[str, str]:
    """Two-sided p for a paired t, and a verdict against 0.05 Bonferroni-corrected.

    p rather than a bare t because p already carries the degrees of freedom, and every
    per-row test on this page has n = 3. There the 0.05 bar is |t| > 4.30, not the ~2 a
    reader carries around -- t = 4.01 at n = 3 is p = 0.057, and was over-read as a result
    at least once while this page was being written.

    p is itself unstable at two degrees of freedom. Read these rows as direction and
    magnitude; the pooled rows are the ones that decide anything.
    """

    if t is None or n < 2:
        return "--", "--"
    p = float(2 * student_t.sf(abs(t), n - 1))
    text = "<0.001" if p < 0.001 else f"{p:.3f}"
    if p < 0.05 / tests:
        return text, ("**p < 0.05**, Bonferroni" if tests > 1 else "**p < 0.05**")
    if p < 0.05:
        return text, "p < 0.05, uncorrected"
    return text, "not significant"


def gap_table(df: pl.DataFrame, caps: dict) -> str:
    """The pk-to-pkd gap for every architecture and input row, paired on seed."""

    lines = [
        "| decoder / encoder | arch | input | seeds | `loss_pk` | `loss_pkd` | gap | t | p |",
        "| ---: | :--- | :--- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for arch in ARCHES:
        for inp in AXIS:
            values = paired(df, arch, inp, "pk", "pkd")
            if not values:
                continue
            mean, _, t = stats(values)
            levels = []
            for loss in ("pk", "pkd"):
                column = df.filter(
                    (pl.col("arch") == arch) & (pl.col("input") == inp) & (pl.col("loss") == loss)
                )[METRIC].to_list()
                m = sum(column) / len(column)
                levels.append(f"{m:.4f}" if len(column) < 2 else f"{m:.4f} ±{stats(column)[1]:.4f}")
            ratio = caps.get(arch, {}).get("ratio")
            lines.append(
                f"| {'--' if ratio is None else f'{ratio:.1f}×'} | `{arch}` | `in_{inp}` | "
                f"{len(values)} | {levels[0]} | {levels[1]} | **{mean:+.4f}** | "
                + ("--" if t is None else f"{t:.2f}") + " | "
                + significance(t, len(values))[0]
                + " |"
            )
    return "\n".join(lines)


def interaction_table(df: pl.DataFrame) -> str:
    """The hypothesis test: does a weaker decoder widen the gap? Paired on seed throughout.

    This, not the per-arch gap, is what the ablation is asking. A gap that is larger under
    a weaker decoder *and* larger than the seed noise on that difference is evidence the
    decoder was absorbing the reconstruction target.
    """

    others = [a for a in ARCHES if a != BASELINE]
    lines = [
        "| arch | input | " + f"`{BASELINE}` gap | this gap | change | sd | t | p | verdict |",
        "| :--- | :--- | ---: | ---: | ---: | ---: | ---: | ---: | :--- |",
    ]
    for arch in others:
        pooled = []
        for inp in AXIS:
            base = paired(df, BASELINE, inp, "pk", "pkd")
            other = paired(df, arch, inp, "pk", "pkd")
            if not base or not other or len(base) != len(other):
                continue
            change = [b - a for a, b in zip(base, other)]
            pooled += change
            mean, sd, t = stats(change)
            p_text, verdict = significance(t, len(change), len(AXIS))
            lines.append(
                f"| `{arch}` | `in_{inp}` | {stats(base)[0]:+.4f} | {stats(other)[0]:+.4f} | "
                f"**{mean:+.4f}** | " + ("--" if sd is None else f"{sd:.4f}") + " | "
                + ("--" if t is None else f"{t:.2f}") + f" | {p_text} | {verdict} |"
            )
        if len(pooled) > 1:
            mean, sd, t = stats(pooled)
            p_text, verdict = significance(t, len(pooled))
            lines.append(
                f"| `{arch}` | **all rows** | | | **{mean:+.4f}** | {sd:.4f} | "
                f"**{t:.2f}** | {p_text} | {verdict} |")
    return "\n".join(lines)


def level_table(df: pl.DataFrame) -> str:
    """What the weaker decoder costs, paired over every cell and seed it shares with the baseline."""

    lines = [
        f"| arch | pairs | mean Δ vs `{BASELINE}` | sd | t | p | wins | verdict |",
        "| :--- | ---: | ---: | ---: | ---: | ---: | ---: | :--- |",
    ]
    for arch in ARCHES:
        if arch == BASELINE:
            continue
        deltas = []
        for inp in AXIS:
            for loss in AXIS:
                def at(a):
                    rows = df.filter(
                        (pl.col("arch") == a) & (pl.col("input") == inp) & (pl.col("loss") == loss)
                    )
                    return dict(zip(rows["seed"], rows[METRIC]))
                mine, base = at(arch), at(BASELINE)
                deltas += [mine[s] - base[s] for s in sorted(set(mine) & set(base))]
        if not deltas:
            continue
        mean, sd, t = stats(deltas)
        p_text, verdict = significance(t, len(deltas))
        lines.append(
            f"| `{arch}` | {len(deltas)} | **{mean:+.4f}** | "
            + ("--" if sd is None else f"{sd:.4f}") + " | "
            + ("--" if t is None else f"{t:.2f}") + f" | {p_text} | "
            f"{sum(d > 0 for d in deltas)}/{len(deltas)} | {verdict} |"
        )
    return "\n".join(lines)


def seed_spread(df: pl.DataFrame) -> str:
    """Seed sd per architecture, pooled over its cells. A weaker decoder may also be noisier."""

    per_cell = (
        df.group_by("arch", "cell")
        .agg(pl.len().alias("n"), pl.col(METRIC).std().alias("sd"))
        .filter(pl.col("n") > 1)
        .group_by("arch")
        .agg(pl.col("n").max().alias("seeds"), pl.len().alias("cells"),
             pl.col("sd").mean().alias("sigma"))
    )
    order = {a: i for i, a in enumerate(ARCHES)}
    rows = sorted(per_cell.iter_rows(named=True), key=lambda r: order.get(r["arch"], 99))
    return "\n".join(
        ["| arch | seeds | cells | seed σ |", "| :--- | ---: | ---: | ---: |"]
        + [f"| `{r['arch']}` | {r['seeds']} | {r['cells']} | {r['sigma']:.4f} |" for r in rows]
    )


def evidence_block() -> list[str]:
    path = HERE / "evidence.json"
    if not path.exists():
        return []
    data = json.loads(path.read_text())
    lines = ["## Supporting measurements", ""]
    for name, entry in data.items():
        lines += [f"**{entry['title']}** — {entry['result']}", "", f"*{entry['note']}*", "",
                  f"`{entry['command']}`", ""]
    return lines


def tables(df: pl.DataFrame) -> str:
    caps = capacity()
    corpora = sorted(df["corpus"].unique())

    parts = [
        f"*{len(df)} probe runs on `{BENCHMARK}`, corpus `{'`, `'.join(corpora)}`. "
        "All differences are paired on the pretraining seed. Regenerate with `gen.py`.*",
        "",
        "## Does weakening the decoder widen the loss-channel gap?",
        "",
        interaction_table(df),
        "",
        "*This is the hypothesis test. `p` is two-sided at that row's own degrees of "
        "freedom, which is why it is reported instead of a bare `t`: with three seeds the "
        "0.05 bar is |t| > 4.30, not the ~2 most readers carry around. Per-row verdicts "
        "are Bonferroni-corrected over the three input rows; the pooled row is those three "
        "together, not a fourth test.*",
        "",
        "## The gap itself, per architecture and input row",
        "",
        gap_table(df, caps),
        "",
        "## What the weaker decoder costs",
        "",
        level_table(df),
        "",
        "*Every cell and seed the two architectures share. A negative mean is a worse "
        "model, whatever the gap does.*",
        "",
        "## Seed spread",
        "",
        seed_spread(df),
        "",
        "## Decoder capacity, derived from the configs",
        "",
        "| arch | enc_depth | dec_depth | dec_dim | encoder GFLOP | decoder GFLOP | ratio |",
        "| :--- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for arch, c in caps.items():
        parts.append(
            f"| `{arch}` | {c['enc_depth']} | {c['dec_depth']} | {c['dec_dim']} | "
            f"{c['encoder_gflops']:.3f} | {c['decoder_gflops']:.3f} | **{c['ratio']:.2f}×** |"
        )
    parts += ["", "*MAE ViT-L's own default sits at 0.35× for comparison. Per sample, at "
              "`mask_ratio` 0.90.*", ""]
    parts += evidence_block()
    return "\n".join(parts)


def measure() -> None:
    """Recompute the two supporting measurements and cache them with their provenance."""

    import sys

    sys.path.insert(0, str(ROOT / "scripts"))
    import torch as t

    from sometria.catalog import MotionViewSpec, build_motion_view

    processed = ROOT / "data" / "processed"
    view = build_motion_view(processed, MotionViewSpec(source_datasets=("AMASS",), min_frames=240))
    g = t.Generator().manual_seed(0)
    picks = t.randperm(len(view), generator=g)[:60].tolist()

    X, Y = [], []
    for i in picks:
        row = view.row(i, named=True)
        sample = t.load(processed / row["motion_path"], weights_only=True)["features"].float()
        sample = sample[t.randperm(sample.shape[0], generator=g)[:200]]
        X.append(sample[..., :4].reshape(len(sample), -1))
        Y.append(sample[..., 4])
    X, Y = t.cat(X), t.cat(Y)

    Xb = t.cat([X, t.ones(len(X), 1)], 1)
    W = t.linalg.solve(Xb.T @ Xb + 1e-3 * t.eye(Xb.shape[1]), Xb.T @ Y)
    residual = ((Y - Xb @ W) ** 2).sum(0)
    total = ((Y - Y.mean(0)) ** 2).sum(0)
    r2 = float(((1 - residual / total.clamp(min=1e-9)) * (total / total.sum())).sum())

    evidence = json.loads((HERE / "evidence.json").read_text()) if (HERE / "evidence.json").exists() else {}
    evidence["tau_recoverable"] = {
        "title": "How much of tau is a function of the channels the encoder already sees",
        "result": f"variance-weighted R² = {r2:.3f} from a *linear* map of (sin, cos, vel, acc), "
                  f"on {len(X):,} frames from 60 AMASS takes",
        "note": "A lower bound: inverse dynamics is tau = M(q)qdd + C(q,qd)qd + G(q) - J^T F_ext, "
                "and linear regression cannot represent the bilinear M(q)qdd term. So the extra "
                "reconstruction target asks for something largely computable from what the "
                "encoder must already encode, which is what a large decoder can absorb.",
        "command": "uv run python results/decoder_capacity/gen.py --measure",
    }
    (HERE / "evidence.json").write_text(json.dumps(evidence, indent=2))
    print(f"tau R2 = {r2:.4f} -> evidence.json")


def splice(readme: Path, generated: str) -> None:
    block = f"{BEGIN}\n\n{generated}\n{END}"
    if readme.exists() and BEGIN in readme.read_text():
        text = readme.read_text()
        head, _, rest = text.partition(BEGIN)
        _, _, tail = rest.partition(END)
        readme.write_text(head + block + tail)
    else:
        readme.write_text(f"# Decoder capacity\n\n{block}\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--measure", action="store_true", help="refresh evidence.json (needs data)")
    args = parser.parse_args()

    if args.measure:
        measure()

    df = collect().sort("arch", "cell", "seed")
    df.write_csv(HERE / "metrics.csv")
    splice(HERE / "README.md", tables(df))
    print(f"{len(df)} runs -> {HERE / 'metrics.csv'} and README.md")


if __name__ == "__main__":
    main()
